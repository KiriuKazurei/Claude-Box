#!/usr/bin/env bash
# Sync guest scripts + config-derived env into a project-local prefix for cloud Linux dry-run.
# Does NOT create a WSL distro. Does NOT install Claude Desktop (see Install-ClaudeDesktop.sh).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=lib/load-config.sh
source "$SCRIPT_DIR/lib/load-config.sh"

ROOT="$(claude_box_repo_root)"
PREFIX="${CLAUDE_BOX_PREFIX:-$(claude_box_default_prefix)}"
CFG="$(claude_box_resolve_config)" || claude_box_die "no config (copy src/wsl-box/config/wsl-box.example.yaml → wsl-box.yaml)"

GUEST_SRC="${ROOT}/src/wsl-box/guest"
GUEST_DST="${PREFIX}/guest"
ENV_DIR="${PREFIX}/env"
BIN_DIR="${PREFIX}/bin"

claude_box_log "repo=$ROOT"
claude_box_log "config=$CFG"
claude_box_log "prefix=$PREFIX"

mkdir -p "$GUEST_DST" "$ENV_DIR" "$BIN_DIR" "${PREFIX}/var"

# Sync guest scripts + lib (idempotent)
shopt -s nullglob
for f in "$GUEST_SRC"/*.sh; do
  base="$(basename "$f")"
  install -m 0755 "$f" "$GUEST_DST/$base"
done
if [[ -d "$GUEST_SRC/lib" ]]; then
  mkdir -p "$GUEST_DST/lib"
  for f in "$GUEST_SRC/lib"/*; do
    [[ -f "$f" ]] || continue
    install -m 0644 "$f" "$GUEST_DST/lib/$(basename "$f")"
    if [[ "$f" == *.sh || "$f" == *.py ]]; then
      chmod 0755 "$GUEST_DST/lib/$(basename "$f")"
    fi
  done
fi
shopt -u nullglob

# Wrapper so PATH can call guest scripts from prefix
cat > "$BIN_DIR/claude-box-guest" << WRAP
#!/usr/bin/env bash
set -euo pipefail
PREFIX=\$(cd "\$(dirname "\$0")/.." && pwd)
name=\${1:?usage: claude-box-guest <script.sh> [args...]}
shift
# shellcheck disable=SC1091
[[ -f "\$PREFIX/env/session.env" ]] && source "\$PREFIX/env/session.env"
exec "\$PREFIX/guest/\$name" "\$@"
WRAP
chmod 0755 "$BIN_DIR/claude-box-guest"

# Write session.env from config (spoof + gateway tips inputs)
{
  echo "# Generated by Install-ClaudeBoxFramework.sh — do not commit"
  echo "# source: $CFG"
  echo "export CLAUDE_BOX_PREFIX=$(printf '%q' "$PREFIX")"
  echo "export CLAUDE_BOX_CONFIG=$(printf '%q' "$CFG")"
  load_config_exports "$CFG"
  # Cloud dry-run: gateway host auto → 127.0.0.1 (no WSL default route needed)
  host_val="$(yaml_scalar "$CFG" host auto)"
  port_val="$(yaml_scalar "$CFG" http_port 3080)"
  if [[ "$host_val" == "auto" || -z "$host_val" ]]; then
    host_val="127.0.0.1"
  fi
  proxy="http://${host_val}:${port_val}"
  echo "export CLAUDE_BOX_GATEWAY_HOST=$(printf '%q' "$host_val")"
  echo "export HTTP_PROXY=$(printf '%q' "$proxy")"
  echo "export HTTPS_PROXY=$(printf '%q' "$proxy")"
  echo "export ALL_PROXY=$(printf '%q' "$proxy")"
  echo "export NO_PROXY=localhost,127.0.0.1"
} > "$ENV_DIR/session.env"

# Stable marker for smoke / structure tests
cat > "${PREFIX}/MANIFEST.txt" << MAN
prefix=$PREFIX
config=$CFG
guest_scripts=$(ls -1 "$GUEST_DST" | tr '\n' ' ')
generated=$(date -Iseconds)
kill_on_local_ip_change=$(yaml_scalar "$CFG" kill_on_local_ip_change false)
oauth_open_in_fingerprint_browser=$(yaml_scalar "$CFG" oauth_open_in_fingerprint_browser true)
identity_vault=$(yaml_scalar "$CFG" identity_vault true)
expose_real_model=$(yaml_scalar "$CFG" expose_real_model true)
hide_identifiers=$(yaml_scalar "$CFG" hide_identifiers true)
host_manufacturer=$(yaml_scalar "$CFG" manufacturer "")
host_product=$(yaml_scalar "$CFG" product "")
MAN

claude_box_log "synced guest → $GUEST_DST"
claude_box_log "session env → $ENV_DIR/session.env"
claude_box_log "next: $SCRIPT_DIR/Run-Smoke.sh"
claude_box_log "Desktop (optional, local deb only): $SCRIPT_DIR/Install-ClaudeDesktop.sh"
